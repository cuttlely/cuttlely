const PG_TRIGGERS = [
    `CREATE OR REPLACE FUNCTION ${S}.pipelines_workspace_required() RETURNS trigger LANGUAGE plpgsql AS $$
    BEGIN
        IF NEW.workspace_id IS NULL OR NEW.workspace_id = '' THEN
            RAISE EXCEPTION 'workspace_required: an ETL pipeline needs a workspace';
        END IF;
        RETURN NEW;
    END $$`,
    `CREATE OR REPLACE TRIGGER pipelines_workspace_insert BEFORE INSERT ON ${S}.pipelines FOR EACH ROW EXECUTE FUNCTION ${S}.pipelines_workspace_required()`,
    `CREATE OR REPLACE TRIGGER pipelines_workspace_update BEFORE UPDATE OF workspace_id ON ${S}.pipelines FOR EACH ROW EXECUTE FUNCTION ${S}.pipelines_workspace_required()`
]

async function schemaExists(session) {
    const { rows } = await session.execute('SELECT EXISTS (SELECT 1 FROM pg_namespace WHERE nspname=$1) AS present', [S])
    return rows[0]?.present === true
}

async function ensureSchema(session) {
    await session.execute(`SELECT pg_advisory_xact_lock(hashtext('cuttlely-etl-schema'))`, [])
    if (!(await schemaExists(session))) {
        await session.execute(`CREATE SCHEMA ${S}`, [])
    }
    for (const sql of PG_SCHEMA) {
        await session.execute(sql, [])
    }
    for (const sql of PG_TRIGGERS) {
        await session.execute(sql, [])
    }
}

// The application database user needs CREATE on the database for a new schema, or USAGE and CREATE on an existing one.
export async function missingPrivilege(source) {
    const session = await source.session()
    try {
        if (!(await schemaExists(session))) {
            const { rows } = await session.execute("SELECT has_database_privilege(current_user, current_database(), 'CREATE') AS ok", [])
            return rows[0]?.ok === true ? null : 'CREATE on the application database'
        }
        const { rows } = await session.execute(
            "SELECT has_schema_privilege(current_user, $1::text, 'USAGE') AND has_schema_privilege(current_user, $1::text, 'CREATE') AS ok",
            [S]
        )
        return rows[0]?.ok === true ? null : `USAGE and CREATE on schema ${S}`
    } finally {
        session.release()
    }
}

export async function openPostgresEtlStore(source) {
    if (!source || typeof source.session !== 'function') {
        throw new Error('ETL Postgres backend: source must have a session() method')
    }
    if (source.dialect !== 'postgres') {
        throw new Error(`ETL Postgres backend: source dialect must be 'postgres', got '${source.dialect}'`)
    }

    const session = await source.session()
    let searchPathSet = false
    try {
        await ensureSchema(session)
        await session.execute(`SET search_path TO ${S}, pg_catalog`, [])
        searchPathSet = true
    } finally {
        session.release()
    }

    let currentSession = null
    let inTransaction = false

    const getSession = async () => {
        if (!currentSession || !searchPathSet) {
            if (currentSession) currentSession.release()
            currentSession = await source.session()
            await currentSession.execute(`SET search_path TO ${S}, pg_catalog`, [])
            searchPathSet = true
        }
        return currentSession
    }

    const query = async (sql, params = []) => {
        const session = await getSession()
        const positional = toPositional(sql)
        const result = await session.execute(positional, params)
        return normalize(result.rows, result.fields)
    }

    return {
        all: async (sql, params) => query(sql, params),
        get: async (sql, params) => (await query(sql, params))[0],
        run: async (sql, params) => {
            const session = await getSession()
            const positional = toPositional(sql)
            const result = await session.execute(positional, params)
            return { changes: result.affected ?? 0 }
        },
        exec: async () => {
            throw new Error('exec is not supported on the Postgres backend')
        },
        tx: async (fn) => {
            const session = await getSession()
            try {
                await session.execute('BEGIN ISOLATION LEVEL READ COMMITTED', [])
                inTransaction = true
                const handle = {
                    all: async (sql, params) => {
                        const positional = toPositional(sql)
                        const result = await session.execute(positional, params)
                        return normalize(result.rows, result.fields)
                    },
                    get: async (sql, params) => {
                        const positional = toPositional(sql)
                        const result = await session.execute(positional, params)
                        const normalized = normalize(result.rows, result.fields)
                        return normalized[0]
                    },
                    run: async (sql, params) => {
                        const positional = toPositional(sql)
                        const result = await session.execute(positional, params)
                        return { changes: result.affected ?? 0 }
                    },
                    exec: async () => {
                        throw new Error('exec is not supported on the Postgres backend')
                    }
                }
                const result = await fn(handle)
                await session.execute('COMMIT', [])
                inTransaction = false
                return result
            } catch (error) {
                inTransaction = false
                try {
                    await session.execute('ROLLBACK', [])
                } catch (rollbackError) {
                    // Session may already be closed
                }
                // Release the session after rollback so the next transaction gets a fresh one
                if (currentSession === session) {
                    currentSession.release()
                    currentSession = null
                    searchPathSet = false
                }
                throw error
            }
        }
    }
}
